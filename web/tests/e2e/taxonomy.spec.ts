// Authentication and private metadata must not enter automatic test artifacts.
test.use({ trace: 'off', screenshot: 'off', video: 'off' })
const text = messages.taxonomy
const settings = messages.settings
type Category = components['schemas']['Category']
type Tag = components['schemas']['Tag']
const input = (page: Page, label: string) => page.getByLabel(new RegExp(`^${label}`))
const editCategory = (page: Page, name: string) => page.getByRole('link', { name: new RegExp(`^${text.editCategory}：${name} \\(`) })
const editTag = (page: Page, name: string) => page.getByRole('link', { name: new RegExp(`^${text.editTag}：${name} \\(`) })
const writesFor = (page: Page) => watchDomainWrites(page, ['/api/v1/categories', '/api/v1/tags'])
async function confirm(page: Page, label: string, uncertain = false) {
  const dialog = page.getByRole('alertdialog')
  const title = dialog.getByRole('heading', { name: uncertain ? text.uncertain : text.reviewTitle, exact: true })
  await expect(title).toBeVisible()
  if (!uncertain) { await expect(title).toBeFocused(); await expect(title).toBeInViewport() }
  await dialog.getByRole('button', { name: label, exact: true }).click()
  await expect(page.getByText(text.done, { exact: true })).toBeVisible()
  await expect(dialog).toHaveCount(0)
}
async function seedCategory(page: Page, origin: string, name: string, parent?: Category): Promise<Category> {
  const response = await page.request.post('/api/v1/categories', { headers: await writeContext(page, origin, parent?.revision), data: { name, parent_id: parent?.id ?? null } })
  expect(response.status()).toBe(200)
  return response.json()
}
async function seedTag(page: Page, origin: string, name: string): Promise<Tag> {
  const response = await page.request.post('/api/v1/tags', { headers: await writeContext(page, origin), data: { name } })
  expect(response.status()).toBe(200)
  return response.json()
}
async function accessible(page: Page) {
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([])
  await noOverflow(page)
}

