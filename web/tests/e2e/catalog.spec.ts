test.use({ trace: 'off', screenshot: 'off', video: 'off' })
const text = messages.catalog
type Item = components['schemas']['Item']
type Category = components['schemas']['Category']
const input = (page: Page, label: string) => page.getByLabel(new RegExp(`^${label}`))
async function confirm(page: Page, label: string) {
  const dialog = page.getByRole('alertdialog')
  await expect(dialog.getByRole('heading', { name: text.reviewTitle, exact: true })).toBeFocused()
  await expect(dialog.getByRole('heading', { name: text.reviewTitle, exact: true })).toBeInViewport()
  await dialog.getByRole('button', { name: label, exact: true }).click()
  await expect(page.getByText(text.done, { exact: true })).toBeVisible()
  await expect(dialog).toHaveCount(0)
}
async function seed(page: Page, origin: string, name: string, categoryID?: string): Promise<Item> {
  const response = await page.request.post('/api/v1/items', { headers: await writeContext(page, origin), data: { name, ...(categoryID ? { category_id: categoryID } : {}) } })
  expect(response.status()).toBe(200)
  return response.json()
}
async function accessible(page: Page) {
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([])
  await noOverflow(page)
}

test('creates, edits, archives, restores and deletes actual catalog metadata through explicit reviews', async ({ page, application }, info) => {
  await provision(page, application)
  const categoryResponse = await page.request.post('/api/v1/categories', { headers: await writeContext(page, application.url), data: { name: '家用品' } })
  expect(categoryResponse.status()).toBe(200)
  const category: Category = await categoryResponse.json()
  const writes = watchDomainWrites(page, ['/api/v1/items'])
  await page.goto('/items')
  await page.getByRole('link', { name: text.create, exact: true }).click()
  await page.getByRole('button', { name: text.review, exact: true }).click()
  await expect(input(page, text.fields.name)).toBeFocused()
  await input(page, text.fields.name).fill('家用濾芯')
  await page.getByRole('checkbox', { name: text.providedBrand, exact: true }).check()
  await expect(page.getByRole('checkbox', { name: text.providedBrand, exact: true })).toBeChecked()
  await page.getByRole('combobox', { name: text.fields.category_id, exact: true }).selectOption(category.id)
  await page.getByRole('link', { name: text.back, exact: true }).click()
  await expect(page.getByRole('heading', { name: text.leaveTitle, exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('alertdialog')).toHaveCount(0)
  await page.getByRole('button', { name: text.review, exact: true }).click()
  expect(writes).toHaveLength(0)
  await accessible(page)
  await confirm(page, text.confirmCreate)
  expect(writes[0]?.proof).toBeUndefined()
  expect(JSON.parse(writes[0]?.body ?? '{}')).toMatchObject({ category_id: category.id, brand: '', model: null, tracking_mode: 'individual', unit_code: 'pcs', base_unit: 'pcs', scale_factor: 1 })
  const id = page.url().split('/').at(-1)!
  await page.getByRole('link', { name: text.edit, exact: true }).click()
  await input(page, text.fields.name).fill('已更名濾芯')
  await page.getByRole('button', { name: text.review, exact: true }).click()
  await confirm(page, text.confirmSave)
  expect(writes[1]?.proof).toBe('"1"')
  expect(JSON.parse(writes[1]?.body ?? '{}')).toEqual({ name: '已更名濾芯' })
  for (const colorScheme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme })
    await expect(page.locator('html')).toHaveAttribute('data-theme', colorScheme)
    await accessible(page)
    await page.screenshot({ path: info.outputPath(`catalog-detail-${colorScheme}.png`), fullPage: true })
  }
  await page.getByRole('button', { name: text.archive, exact: true }).click()
  await input(page, text.reason).fill('保留既有紀錄')
  await page.getByRole('button', { name: text.review, exact: true }).click()
  await expect(page.getByRole('alertdialog')).toContainText(text.archiveHelp)
  await confirm(page, text.confirmArchive)
  expect(writes[2]?.proof).toBe('"2"')
  await page.getByRole('button', { name: text.restore, exact: true }).click()
  await confirm(page, text.confirmRestore)
  expect(JSON.parse(writes[3]?.body ?? '{}')).toEqual({ status: 'active' })
  await page.getByRole('button', { name: text.delete, exact: true }).click()
  await expect(page.getByRole('alertdialog')).toContainText(text.deleteHelp)
  await confirm(page, text.confirmDelete)
  await expect(page.getByRole('heading', { name: text.empty, exact: true })).toBeVisible()
  expect(writes).toHaveLength(5)
  expect(writes[4]?.proof).toBe('"4"')
  expect((await page.request.get(`/api/v1/items/${id}`)).status()).toBe(404)
})

test('returns from real login and explicitly adopts concurrent metadata without reconnect replay', async ({ page, application }) => {
  const password = await provision(page, application)
  const item = await seed(page, application.url, 'Original')
  await page.context().clearCookies()
  await page.goto(`/items/${item.id}/edit`)
  await expect(page.getByRole('heading', { name: messages.auth.loginHeading, exact: true })).toBeVisible()
  await input(page, messages.auth.username).fill('owner')
  await input(page, messages.auth.password).fill(password)
  await page.getByRole('button', { name: messages.auth.login, exact: true }).click()
  await expect(input(page, text.fields.name)).toHaveValue('Original')
  const writes = watchDomainWrites(page, ['/api/v1/items'])
  await input(page, text.fields.name).fill('Local edit')
  const changed = await page.request.patch(`/api/v1/items/${item.id}`, { headers: await writeContext(page, application.url, item.revision), data: { name: 'Concurrent edit', brand: 'Remote brand' } })
  expect(changed.status()).toBe(200)
  await page.getByRole('button', { name: text.refresh, exact: true }).click()
  await expect(page.getByText(text.changed, { exact: true })).toBeVisible()
  await expect(input(page, text.fields.name)).toHaveValue('Local edit')
  await expect(page.getByRole('button', { name: text.review, exact: true })).toBeDisabled()
  await page.getByRole('button', { name: text.keepEdits, exact: true }).click()
  await expect(input(page, text.fields.brand)).toHaveValue('Remote brand')
  await page.context().setOffline(true)
  await expect(page.getByText(text.offline, { exact: true })).toBeVisible()
  await page.context().setOffline(false)
  await expect(page.getByRole('button', { name: text.review, exact: true })).toBeEnabled()
  expect(writes).toHaveLength(0)
  await page.getByRole('button', { name: text.review, exact: true }).click()
  await confirm(page, text.confirmSave)
  expect(writes).toHaveLength(1)
  expect(writes[0]?.proof).toBe('"2"')
  expect(JSON.parse(writes[0]?.body ?? '{}')).toEqual({ name: 'Local edit' })
})

test('reconciles a genuinely committed malformed catalog deletion only with the original request', async ({ page, application }) => {
  await provision(page, application)
  const item = await seed(page, application.url, 'Unknown deletion')
  let attempts = 0
  const replies: string[] = []
  await page.route(`**/api/v1/items/${item.id}`, async (route) => {
    if (route.request().method() !== 'DELETE') { await route.continue(); return }
    const response = await route.fetch()
    replies.push(await response.text())
    if (++attempts === 1) await route.fulfill({ response, body: '{"ok":false}' })
    else await route.fulfill({ response })
  })
  const writes = watchDomainWrites(page, ['/api/v1/items'])
  await page.goto(`/items/${item.id}`)
  await page.getByRole('button', { name: text.delete, exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: text.confirmDelete, exact: true }).click()
  await expect(page.getByRole('heading', { name: text.uncertain, exact: true })).toBeVisible()
  await page.getByRole('alertdialog').getByRole('button', { name: text.cancel, exact: true }).click()
  await expect(page.getByRole('alertdialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: text.delete, exact: true })).toBeDisabled()
  await page.getByRole('button', { name: text.readCurrent, exact: true }).click()
  await page.context().setOffline(true)
  await page.context().setOffline(false)
  expect(writes).toHaveLength(1)
  await page.getByRole('button', { name: text.openOriginal, exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: text.retryOriginal, exact: true }).click()
  await expect(page.getByText(text.done, { exact: true })).toBeVisible()
  expect(attempts).toBe(2)
  expect(writes[1]).toEqual(writes[0])
  expect(replies[1]).toBe(replies[0])
  expect((await page.request.get(`/api/v1/items/${item.id}`)).status()).toBe(404)
})

