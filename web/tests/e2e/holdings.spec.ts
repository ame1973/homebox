const input = (page: Page, label: string) => page.getByLabel(new RegExp(`^${label}`))
const watch = (page: Page) => watchDomainWrites(page, ['/api/v1/items', '/api/v1/units', '/api/v1/stock'])
async function seedItem(page: Page, origin: string, quantity = false): Promise<Item> {
  const response = await page.request.post('/api/v1/items', { headers: await writeContext(page, origin), data: { name: quantity ? '數量畫面測試物品' : '個體畫面測試物品', ...(quantity ? { tracking_mode: 'quantity', unit_code: 'kg', base_unit: 'g', scale_factor: 1000 } : {}) } })
  expect(response.status()).toBe(200)
  return response.json()
}
async function seedLocation(page: Page, origin: string, code: string): Promise<Location> {
  const response = await page.request.post('/api/v1/locations', { headers: await writeContext(page, origin), data: { name: `實際位置 ${code}`, code } })
  expect(response.status()).toBe(200)
  return response.json()
}
async function seedUnit(page: Page, origin: string, item: Item, location: Location | null): Promise<Unit> {
  const response = await page.request.post(`/api/v1/items/${item.id}/units`, { headers: await writeContext(page, origin, item.revision), data: { location_id: location?.id ?? null, notes: 'Original note', serial_number: null } })
  expect(response.status()).toBe(200)
  return response.json()
}
async function currentItem(page: Page, id: string): Promise<Item> {
  const response = await page.request.get(`/api/v1/items/${id}`)
  expect(response.status()).toBe(200)
  return response.json()
}
async function seedStock(page: Page, origin: string, item: Item, location: Location, quantity_base: number) {
  const response = await page.request.post('/api/v1/stock/receive', { headers: await writeContext(page, origin, item.revision), data: { item_id: item.id, target_location_id: location.id, quantity_base } })
  expect(response.status()).toBe(200)
}
async function confirm(page: Page, label: string) {
  const dialog = page.getByRole('alertdialog')
  await expect(dialog.getByRole('heading', { name: text.reviewTitle, exact: true })).toBeFocused()
  await expect(dialog.getByRole('heading', { name: text.reviewTitle, exact: true })).toBeInViewport()
  await dialog.getByRole('button', { name: label, exact: true }).click()
  await expect(page.getByText(text.done, { exact: true })).toBeVisible()
  await expect(dialog).toHaveCount(0)
}
async function accessible(page: Page) {
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations).toEqual([])
  await noOverflow(page)
}

