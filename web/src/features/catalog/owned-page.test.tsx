function page<T>(rows: T[], query: { cursor?: string; limit?: number }) {
  const start = Number(query.cursor ?? 0)
  const end = start + (query.limit ?? 100)
  return { data: rows.slice(start, end), next_cursor: rows.length > end ? String(end) : null }
}
